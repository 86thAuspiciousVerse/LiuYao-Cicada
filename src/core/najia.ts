import type { TrigramName, DiZhi } from './types';

/**
 * 纳甲地支全表 (浑天甲子歌诀)
 *
 * 根据京房纳甲体系，八纯卦各纳六爻地支：
 *   阳四卦(乾震坎艮)用阳支(子寅辰午申戌)顺排
 *   阴四卦(坤巽离兑)用阴支(丑亥酉未巳卯)逆排
 *   外卦初爻(四爻) = 内卦初爻的六冲地支 (隔八相生)
 *
 * 完整纳甲表 (六爻地支，从初爻到上爻):
 *   乾☰ 金: 子水 寅木 辰土 午火 申金 戌土
 *   震☳ 木: 子水 寅木 辰土 午火 申金 戌土  (与乾同)
 *   坎☵ 水: 寅木 辰土 午火 申金 戌土 子水
 *   艮☶ 土: 辰土 午火 申金 戌土 子水 寅木
 *
 *   坤☷ 土: 未土 巳火 卯木 丑土 亥水 酉金
 *   巽☴ 木: 丑土 亥水 酉金 未土 巳火 卯木
 *   离☲ 火: 卯木 丑土 亥水 酉金 未土 巳火
 *   兑☱ 金: 巳火 卯木 丑土 亥水 酉金 未土
 */

/** 纳甲地支查找表: 卦名 → [初爻地支, 二爻, 三爻, 四爻, 五爻, 上爻] */
const NAJIA_DIZHI: Record<TrigramName, DiZhi[]> = {
  乾: ['子', '寅', '辰', '午', '申', '戌'],
  震: ['子', '寅', '辰', '午', '申', '戌'],
  坎: ['寅', '辰', '午', '申', '戌', '子'],
  艮: ['辰', '午', '申', '戌', '子', '寅'],
  坤: ['未', '巳', '卯', '丑', '亥', '酉'],
  巽: ['丑', '亥', '酉', '未', '巳', '卯'],
  离: ['卯', '丑', '亥', '酉', '未', '巳'],
  兑: ['巳', '卯', '丑', '亥', '酉', '未'],
};

// ---------- 公开函数 ----------

/**
 * 获取八卦的完整纳甲地支数组
 *
 * @param trigram 八卦名称 (如 '乾', '坤')
 * @returns 长度为 6 的地支数组，索引 0-5 对应初爻到上爻
 */
export function getNaJiaDizhi(trigram: TrigramName): DiZhi[] {
  // 返回浅拷贝副本，防止外部修改内部表
  return [...NAJIA_DIZHI[trigram]];
}

/**
 * 获取变卦动爻的新地支
 *
 * 当本卦某爻发生变动时（阴阳互变），该爻所在的上卦或下卦变为新卦，
 * 此函数返回新卦中对应爻位的地支。
 *
 * @param newTrigram 变卦后动爻所在的新上卦或下卦名称
 * @param yaoIndex   动爻在本卦中的位置 (0-5, 初爻=0, 上爻=5)
 * @returns 该爻在变卦中的地支
 */
export function getChangedDizhi(newTrigram: TrigramName, yaoIndex: number): DiZhi {
  const dizhi = NAJIA_DIZHI[newTrigram];
  if (yaoIndex < 0 || yaoIndex > 5) {
    throw new Error(`爻位索引超出范围: ${yaoIndex}，有效范围 0-5`);
  }
  return dizhi[yaoIndex];
}
